export function readTheme(): Theme {
	try {
		const saved = localStorage.getItem("recodex-theme");
		return themes.find((theme) => theme.id === saved) ?? themes[0];
	} catch {
		return themes[0];
	}
}

export function applyTheme(theme: Theme) {
	const root = document.documentElement;
	root.dataset.theme = theme.id;
	root.classList.toggle("dark", theme.mode === "dark");
	root.style.colorScheme = theme.mode;
	for (const [name, value] of Object.entries(theme.colors)) {
		root.style.setProperty(`--${name}`, value);
	}
	try {
		localStorage.setItem("recodex-theme", theme.id);
	} catch {
		// Keep theme switching available when persistent storage is unavailable.
	}
}
